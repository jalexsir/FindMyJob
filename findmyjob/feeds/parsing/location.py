"""Визначення міста / формату роботи з тексту вакансії."""

from __future__ import annotations

import re

from .text import unescape_twice

# Місто визначити не вдалося — відсилаємо людину туди, де воно точно є.
UNKNOWN_LOCATION = "в посиланні"
REMOTE_LOCATION = "Віддалено"

# Форма в тексті → нормальна назва міста
CITY_FORMS: dict[str, str] = {
    "києві": "Київ", "київ": "Київ",
    "львові": "Львів", "львів": "Львів",
    "одесі": "Одеса", "одеса": "Одеса",
    "дніпрі": "Дніпро", "дніпро": "Дніпро",
    "білій церкві": "Біла Церква", "біла церква": "Біла Церква",
    "вінниці": "Вінниця", "вінниця": "Вінниця",
    "харкові": "Харків", "харків": "Харків",
    "івано-франківську": "Івано-Франківськ", "івано-франківськ": "Івано-Франківськ",
    "тернополі": "Тернопіль", "тернопіль": "Тернопіль",
    "ужгороді": "Ужгород", "ужгород": "Ужгород",
    "луцьку": "Луцьк", "луцьк": "Луцьк",
    "рівному": "Рівне", "рівне": "Рівне",
    "житомирі": "Житомир", "житомир": "Житомир",
    "запоріжжі": "Запоріжжя", "запоріжжя": "Запоріжжя",
    "кривому розі": "Кривий Ріг", "кривий ріг": "Кривий Ріг",
}

# Спочатку довші форми, щоб "кривому розі" перевірялось раніше за "кривому"
_CITY_FORMS_SORTED = sorted(CITY_FORMS, key=len, reverse=True)

_REMOTE_RE = re.compile(
    r"(?:формат роботи[:\s—-]+віддален|віддален\w*\s+формат роботи)"
)


def extract_location(entry) -> str:
    """Витягує місто з title/description через словник форм назв міст.

    Також розпізнає "формат роботи: віддалено". Викликається лише для Djinni —
    у DOU локація вже витягнута з `<title>` (див. dou_title.parse_dou_title).
    """
    raw = " ".join([
        getattr(entry, "title", ""),
        getattr(entry, "summary", "") or getattr(entry, "description", ""),
    ])
    text = unescape_twice(raw).lower()

    if _REMOTE_RE.search(text):
        return REMOTE_LOCATION

    for form in _CITY_FORMS_SORTED:
        if form in text:
            return CITY_FORMS[form]

    return UNKNOWN_LOCATION
